/** One field an authorable node kind carries. */
export interface AuthoringFieldDescriptor {
  name: string;
  required: boolean;
  /** A short, stable, human/machine readable type description — not a TypeScript type. */
  type: string;
  /** Other semantic node kinds this field's value (a `NodeId` or `NodeId[]`) may reference. */
  referenceTargets?: readonly SemanticNodeKind[];
  /** The closed vocabulary this field's value is drawn from, when it has one. */
  closedEnum?: readonly string[];
  description: string;
}

/** Every publicly authorable graph-model semantic node kind, structurally described. */
export interface AuthoringKindDescriptor {
  kind: SemanticNodeKind;
  purpose: string;
  fields: AuthoringFieldDescriptor[];
  /** A minimal valid shape. `NodeId`/`FieldId` values are placeholders (`"<id>"`). */
  template: Record<string, unknown>;
}

