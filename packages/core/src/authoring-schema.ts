/**
 * Canonical machine-readable authoring metadata (spec16 §67-78).
 *
 * An AI agent constructing or modifying an Axiom graph must not have to guess valid node
 * shapes, valid references, closed vocabularies or required fields from source code. This
 * module is the **single** structured description of every publicly authorable semantic
 * node kind — the same eighteen kinds `SEMANTIC_NODE_KINDS` enumerates — derived from the
 * same closed vocabularies validation and the runtime already use (`OPERATION_KINDS`,
 * `EDGE_KINDS`, `EXPRESSION_KINDS`, `WORKFLOW_STEP_TYPES`, `AUTHORIZATION_OPERATIONS`, …)
 * rather than duplicating them by hand (spec16 §71).
 *
 * It is deliberately scoped to the **graph model** — `EntityDef` through
 * `AuthorizationPolicyDef` — not the nine UI node kinds. UI authoring already has its own
 * canonical, mechanically-checked machine catalogue (`@cynodia/axiom-ui`'s
 * `packages/ui-toolkit/docs/PATTERN_CATALOG.json`, generated by `npm run toolkit:catalog`);
 * a second description of the same nodes here would be exactly the "four unrelated sources
 * of truth" spec16 §71 warns against, so `docs/UI.md` and the toolkit catalogue remain that
 * authority.
 *
 * A template is a **minimal valid shape**, not a set of defaults: it never assigns
 * security-sensitive semantics an author did not ask for (spec16 §78) — an `ActionDef`
 * template carries no `authorizationPolicy`, which is exactly its pre-0.15 public contract,
 * not a silently-inserted permission.
 */

