const BY_KIND = new Map<SemanticNodeKind, AuthoringKindDescriptor>(KINDS.map((d) => [d.kind, d]));

/** Every graph-model semantic node kind an agent may author (spec16 §72). */
export function listAuthorableKinds(): readonly SemanticNodeKind[] {
  return SEMANTIC_NODE_KINDS;
}

/** The structural authoring contract for one node kind, or `undefined` for an unknown kind. */
export function describeAuthoringKind(kind: string): AuthoringKindDescriptor | undefined {
  return BY_KIND.get(kind as SemanticNodeKind);
}

/** The complete authoring schema — one descriptor per authorable graph-model kind (spec16 §69, §70). */
export function authoringSchema(): readonly AuthoringKindDescriptor[] {
  return KINDS;
}

/** Every edge kind the graph can derive, for tooling that renders `getEdges` results. */
export function authoringEdgeKinds(): readonly string[] {
  return EDGE_KINDS;
}
