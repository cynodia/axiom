/**
 * `axiom.conformance.v10` — the tooling/explainability conformance tier (spec16 §123-126).
 *
 * Server IR conformance (`axiom.conformance.v1`-`v9`, `packages/server/conformance/`) checks
 * that a portable *execution* document produces a required result on a real backend
 * (memory/SQLite). AgentAPI carries no execution semantics of its own — it is static
 * analysis over a graph — so this tier checks the **tooling contract** instead: given a
 * graph, does each canonical inspection/analysis/authoring/editing entry point produce the
 * result independently specified below (spec16 §121, §125 — expectations are hand-written,
 * never generated by calling the implementation under test).
 *
 * Each fixture is self-contained (builds its own tiny graph) so a fixture can be read and
 * verified without cross-referencing another.
 */
export const TOOLING_CONFORMANCE_CONTRACT = 'axiom.conformance.v10';

export type ToolingConformanceCategory =
  | 'inventory'
  | 'dependencies'
  | 'explain-action'
  | 'explain-query'
  | 'explain-workflow'
  | 'authorization-analysis'
  | 'capabilities'
  | 'semantic-diff'
  | 'diagnostics'
  | 'authoring-schema'
  | 'graph-edit'
  | 'native-boundary';

export interface ToolingConformanceFixture {
  id: string;
  category: ToolingConformanceCategory;
  description: string;
  run: () => unknown;
  expected: unknown;
}

export interface ToolingConformanceResult {
  id: string;
  category: ToolingConformanceCategory;
  passed: boolean;
  actual?: unknown;
  expected?: unknown;
  error?: string;
}

function deepEqual(a: unknown, b: unknown): boolean {
  return JSON.stringify(sortKeysDeep(a)) === JSON.stringify(sortKeysDeep(b));
}

function sortKeysDeep(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(sortKeysDeep);
  if (value && typeof value === 'object') {
    return Object.fromEntries(
      Object.entries(value as Record<string, unknown>)
        .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
        .map(([k, v]) => [k, sortKeysDeep(v)]),
    );
  }
  return value;
}

