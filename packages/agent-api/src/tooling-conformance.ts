const E_USER = nodeId('ct_entity_user');
const F_UID = fieldId('ct_field_uid');
const F_ROLE = fieldId('ct_field_role');
const S_COUNT = nodeId('ct_state_count');
const A_BUMP = nodeId('ct_action_bump');
const A_NATIVE = nodeId('ct_action_native');
const Q_USERS = nodeId('ct_query_users');
const P_ADMIN = nodeId('ct_policy_admin');
const ROW = nodeId('ct_row');

function fixtureGraph(): ApplicationGraph {
  const g = new ApplicationGraph('ct-graph', 'Conformance Fixture');
  g.addNode<EntityDef>({
    id: E_USER,
    kind: 'entity',
    identityFieldId: F_UID,
    fields: [
      { id: F_UID, valueType: primitiveType('string'), required: true },
      { id: F_ROLE, valueType: primitiveType('string'), required: true },
    ],
  });
  g.setPrincipalEntity(E_USER);
  g.addNode<StateDef>({ id: S_COUNT, kind: 'state', authority: 'server', valueType: primitiveType('number'), initialValue: 0 });
  g.addNode<AuthorizationPolicyDef>({
    id: P_ADMIN,
    kind: 'authorization-policy',
    allow: binary('eq', field(ref(nodeId('axiom_principal')), F_ROLE), literal('admin')),
  });
  g.addNode<ActionDef>({
    id: A_BUMP,
    kind: 'action',
    authorizationPolicy: P_ADMIN,
    operations: [{ kind: 'set', target: stateLocation(S_COUNT), value: binary('add', ref(S_COUNT), literal(1)) }],
  });
  g.addNode<ActionDef>({ id: A_NATIVE, kind: 'action', operations: [{ kind: 'native', implementationId: 'legacy.op' }] });
  g.addNode<QueryDef>({
    id: Q_USERS,
    kind: 'query',
    source: E_USER,
    rowScopeId: ROW,
    authorizationPolicy: P_ADMIN,
    pagination: { strategy: 'offset', maxPageSize: 50 },
  } as QueryDef);
  return g;
}

/**
 * A self-contained entity + query + (optionally referenced) read policies, for the F3
 * attach/detach/replace fixtures. `declarePolicies` names every `ReadPolicyDef` node to
 * declare (both, for a "replace" scenario), independent of which one `readPolicyId` points
 * at, so the diff reflects only the reference change, not a policy node appearing/vanishing.
 */
function readPolicyFixtureGraph(readPolicyId: string | undefined, ...declarePolicies: string[]): ApplicationGraph {
  const g = new ApplicationGraph('ct-read-policy-graph', 'Read Policy Fixture');
  const entityId = nodeId('read_policy_entity');
  const identityField = fieldId('read_policy_entity_id');
  g.addNode<EntityDef>({
    id: entityId,
    kind: 'entity',
    identityFieldId: identityField,
    fields: [{ id: identityField, valueType: primitiveType('string'), required: true }],
  });
  for (const policyId of new Set([...(readPolicyId ? [readPolicyId] : []), ...declarePolicies])) {
    g.addNode<ReadPolicyDef>({
      id: nodeId(policyId),
      kind: 'read-policy',
      entityId,
      rowScopeId: nodeId('read_policy_row'),
      predicate: literal(true),
    });
  }
  g.addNode<QueryDef>({
    id: nodeId('read_policy_query'),
    kind: 'query',
    source: entityId,
    rowScopeId: nodeId('read_policy_query_row'),
    pagination: { strategy: 'offset', maxPageSize: 50 },
    ...(readPolicyId ? { readPolicyId: nodeId(readPolicyId) } : {}),
  } as QueryDef);
  return g;
}

