export function runToolingConformanceFixture(fixture: ToolingConformanceFixture): ToolingConformanceResult {
  try {
    const actual = fixture.run();
    return { id: fixture.id, category: fixture.category, passed: deepEqual(actual, fixture.expected), actual, expected: fixture.expected };
  } catch (error) {
    return { id: fixture.id, category: fixture.category, passed: false, error: error instanceof Error ? error.message : String(error) };
  }
}

export function runToolingConformanceSuite(): ToolingConformanceResult[] {
  return toolingConformanceFixtures().map(runToolingConformanceFixture);
}
